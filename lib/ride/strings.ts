export const rideStrings: Record<RideLanguage, RideDictionary> = { en, hi, es };

export function translateRide(language: RideLanguage, key: RideStringKey, values?: Record<string, string | number>): string {
  let text = rideStrings[language][key] ?? en[key];
  if (values) for (const [name, value] of Object.entries(values)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}
